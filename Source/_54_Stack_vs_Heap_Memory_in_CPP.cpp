    // 系统会先将整个程序载入内存 并分配大量物理内存空间供应用程序运行使用
    // 栈和堆正是内存中的两个关键区域 栈内存通常是固定大小的存储区域
    // 默认大小约为2MB左右 堆内存也有默认的初始容量 但会随着程序运行动态调整大小
